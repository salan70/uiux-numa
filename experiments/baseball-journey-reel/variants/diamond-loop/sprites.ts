/** ドット文字の幅（点の数）。字の間は 1 点あける。 */
export const dotWidth = (text: string) => Math.max(0, text.length * 6 - 1);

/**
 * 文字列を点灯する点の座標 [列, 行] に展開する。
 * 列の順に並べて返すので、呼び出し側は列から時刻を引いて左から点灯させられる。
 */
export function dotCells(text: string): [number, number][] {
  const cells: [number, number][] = [];
  [...text].forEach((ch, i) => {
    const glyph = GLYPHS[ch] ?? GLYPHS[" "];
    for (let row = 0; row < 7; row++)
      for (let col = 0; col < 5; col++) if (glyph[row][col] === "#") cells.push([i * 6 + col, row]);
  });
  return cells.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
}
