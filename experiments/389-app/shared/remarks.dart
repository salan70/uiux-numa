/// 今日の1問で 3 回外れたときだけに足す一言。
const _failedDaily = ['3 回とも外れ。', 'スリーアウト、チェンジ。', '今日はこの選手に軍配。'];

/// 結果の一言を 1 つ選ぶ。random を渡せば選び方を固定できる（撮影のため）。
String pickRemark(QuizSession s, {math.Random? random}) {
  final r = random ?? math.Random();
  final pool = [..._remarks[s.finalRank]!, if (s.status == QuizStatus.failed) ..._failedDaily];
  return pool[r.nextInt(pool.length)].replaceAll('{n}', '${s.unveil}');
}
